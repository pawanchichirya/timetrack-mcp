"""
TimeTrack persistence layer using PostgreSQL (Neon).

Shared by the FastAPI website and MCP server.
Requires the DATABASE_URL environment variable.
"""

import os
import psycopg
from psycopg.rows import dict_row


def get_connection():
    """Open a connection to the PostgreSQL database."""
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError(
            "DATABASE_URL environment variable is not configured."
        )

    return psycopg.connect(
        database_url,
        row_factory=dict_row,
        connect_timeout=10,
    )


def init_db():
    """Create the time_entries table if it doesn't exist."""
    with get_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS time_entries (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                employee_name TEXT NOT NULL,
                project TEXT NOT NULL,
                entry_date DATE NOT NULL,
                hours DOUBLE PRECISION NOT NULL
                    CHECK (hours > 0),
                description TEXT NOT NULL DEFAULT ''
            )
        """)


def _row_to_dict(row) -> dict:
    """Convert a database row to the existing API response format."""
    return {
        "id": row["id"],
        "employee_name": row["employee_name"],
        "project": row["project"],
        "entry_date": (
            row["entry_date"].isoformat()
            if hasattr(row["entry_date"], "isoformat")
            else row["entry_date"]
        ),
        "hours": row["hours"],
        "description": row["description"],
    }


def list_all_entries() -> list[dict]:
    """Return all time entries, newest first."""
    with get_connection() as conn:
        rows = conn.execute("""
            SELECT *
            FROM time_entries
            ORDER BY entry_date DESC, id DESC
        """).fetchall()

    return [_row_to_dict(row) for row in rows]


def log_time(
    employee_name: str,
    project: str,
    entry_date: str,
    hours: float,
    description: str = "",
) -> dict:
    """Insert a time entry and return the created entry."""
    if hours <= 0:
        raise ValueError("hours must be a positive number")

    with get_connection() as conn:
        row = conn.execute(
            """
            INSERT INTO time_entries
                (employee_name, project, entry_date, hours, description)
            VALUES (%s, %s, %s, %s, %s)
            RETURNING *
            """,
            (employee_name, project, entry_date, hours, description),
        ).fetchone()

    return _row_to_dict(row)


def get_timesheet(
    employee_name: str,
    start_date: str | None = None,
    end_date: str | None = None,
) -> list[dict]:
    """Return an employee's entries, optionally filtered by date."""
    query = """
        SELECT *
        FROM time_entries
        WHERE employee_name = %s
    """
    params = [employee_name]

    if start_date:
        query += " AND entry_date >= %s"
        params.append(start_date)

    if end_date:
        query += " AND entry_date <= %s"
        params.append(end_date)

    query += " ORDER BY entry_date, id"

    with get_connection() as conn:
        rows = conn.execute(query, params).fetchall()

    return [_row_to_dict(row) for row in rows]


def execute_query(query: str, params: list | None = None) -> list[dict]:
    """Execute a SELECT query and return its rows as dictionaries."""
    with get_connection() as conn:
        rows = conn.execute(query, params or []).fetchall()

    return [_row_to_dict(row) for row in rows]


def list_projects() -> list[str]:
    """Return all projects that have at least one logged entry."""
    with get_connection() as conn:
        rows = conn.execute("""
            SELECT DISTINCT project
            FROM time_entries
            ORDER BY project
        """).fetchall()

    return [row["project"] for row in rows]


def get_project_summary(project: str) -> dict:
    """Return total hours per employee for a project."""
    with get_connection() as conn:
        rows = conn.execute(
            """
            SELECT employee_name, SUM(hours) AS total_hours
            FROM time_entries
            WHERE project = %s
            GROUP BY employee_name
            ORDER BY employee_name
            """,
            (project,),
        ).fetchall()

    if not rows:
        raise ValueError(
            f"No time logged against project '{project}'"
        )

    by_employee = {
        row["employee_name"]: float(row["total_hours"])
        for row in rows
    }

    return {
        "project": project,
        "total_hours": sum(by_employee.values()),
        "by_employee": by_employee,
    }
